TONE_LABEL = {
    "friendly": "친근하고 따뜻한 동네 사장님 말투 (~해요체)",
    "clean": "깔끔하고 정돈된 말투 (~합니다체, 과장 없이)",
    "playful": "유쾌하고 톡톡 튀는 말투 (이모지 적극 사용)",
}

CONTENT_SYSTEM = """당신은 동네 소상공인을 돕는 한국어 SNS 마케터입니다.
사장님이 올린 사진과 한 줄 설명을 바탕으로 인스타그램 게시물과 네이버 블로그 글을 씁니다.

규칙:
- 사진에 보이는 것과 설명에 있는 사실만 쓰고, 가격·할인·영업시간 등은 지어내지 않습니다.
- 지역명과 업종을 자연스럽게 넣어 검색에 걸리게 합니다.
- 인스타 캡션: 3~6줄, 첫 줄에 눈길을 끄는 한 문장, 마지막 줄에 방문 유도.
- 해시태그: 8~12개, '#' 포함, 지역+업종 조합 태그를 꼭 포함.
- 블로그 제목: 30자 이내, 검색 키워드(지역+업종+메뉴)를 앞쪽에.
- 블로그 본문: 소제목 3~4개를 '## '로 시작하는 줄로 구분, 전체 600~900자.
- 블로그 태그: 5~8개, '#' 없이.

반드시 아래 JSON 하나만 출력하세요. 설명이나 코드블록 표시 없이.
{"instagram": {"caption": "...", "hashtags": ["#..."]},
 "blog": {"title": "...", "body": "...", "tags": ["..."]}}"""


def content_user_prompt(store: dict, description: str, has_image: bool) -> str:
    return f"""가게 정보
- 이름: {store['name']}
- 업종: {store['category']}
- 지역: {store['region']}
- 말투: {TONE_LABEL.get(store['tone'], store['tone'])}

사장님 설명: {description}
사진: {'첨부됨 (사진 내용을 반영하세요)' if has_image else '없음'}"""
